/* Build S04FixtureCore.gs from s04/fixture.js.
 * Strips module.exports, wraps in IIFE as global S04Fixture. */
const fs = require('node:fs');

function buildFixture() {
  let code = fs.readFileSync('s04/fixture.js', 'utf8');

  // Remove the module.exports block
  code = code.replace(/\nmodule\.exports = \{[\s\S]*?\};/, '');

  // Wrap in IIFE, exposing the relevant exports
  const lines = code.split('\n');
  const exportNames = ['dryRun', 'apply', 'validate', 'enableFn01', 'disableFn01',
    'DEV_SHEET_ID', 'TEST_EMAIL', 'SYNTHETIC_JOB_INTERNAL_ID', 'SYNTHETIC_TASK_ID',
    'buildSyntheticJob', 'buildSyntheticTask'];

  return '/* GENERATED by node scripts/build-s04-fixture.cjs — do not edit. */\n' +
    'var S04Fixture = (function() {\n' +
    code + '\n' +
    'return { ' + exportNames.map(n => n + ': ' + n).join(', ') + ' };\n' +
    '})();\n';
}

if (require.main === module) {
  fs.writeFileSync('apps-script/S04FixtureCore.gs', buildFixture());
  console.log('Built apps-script/S04FixtureCore.gs');
}

module.exports = { buildFixture };
