/* Build G04NegativeCore.gs from s04/g04-negative.js.
 * Strips module.exports, wraps in IIFE as global G04Tests. */
const fs = require('node:fs');

function buildG04() {
  let code = fs.readFileSync('s04/g04-negative.js', 'utf8');

  // Remove the module.exports block
  code = code.replace(/\nmodule\.exports = \{[\s\S]*?\};/, '');

  const exportNames = [
    'buildJob', 'buildTask', 'upsertJob', 'upsertTask',
    'enableFn01', 'disableFn01', 'setFn01', 'getFn01',
    'makeCommand', 'snapshotTask', 'countByCommit', 'makeResult',
    'testDisabledMode', 'testStaleVersion', 'testDuplicateReplay',
    'testCommandMismatch', 'testOutOfPilot', 'restoreSafeState'
  ];

  return '/* GENERATED by node scripts/build-s04-g04.cjs — do not edit. */\n' +
    'var G04Tests = (function() {\n' +
    code + '\n' +
    'return { ' + exportNames.map(n => n + ': ' + n).join(', ') + ' };\n' +
    '})();\n';
}

if (require.main === module) {
  fs.writeFileSync('apps-script/s04/G04NegativeCore.gs', buildG04());
  console.log('Built apps-script/s04/G04NegativeCore.gs');
}

module.exports = { buildG04 };
