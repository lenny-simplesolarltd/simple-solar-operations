/* Build S05Core.gs from s05/mapping.js and s05/intake.js.
 * Strips require/module.exports, wraps in IIFE as global S05Core. */
const fs = require('node:fs');

function buildS05Core() {
  const modules = ['s05/mapping.js', 's05/intake.js'];
  const names = { 's05/mapping.js': 'm0', 's05/intake.js': 'm1' };

  const sections = modules.map(file => {
    let code = fs.readFileSync(file, 'utf8');
    // Replace require calls with module references
    code = code.replace(/require\('\.\/mapping\.js'\)/g, names['s05/mapping.js']);
    // Strip module.exports
    code = code.replace(/\nmodule\.exports = \{[\s\S]*?\};/, '');

    let exports;
    if (file === 's05/mapping.js') {
      exports = '{ clone, buildFieldMap, extractField, applyMappings, buildSyntheticMapping, resolveBookingJob, generateJobId, generateInternalJobId, generateCustomerId }';
    } else {
      exports = '{ createIntakeProcessor, processSoldIntake, processBookingIntake, validateIntake, intakeHash, buildIntakeRecord, buildCustomer, buildJob, generateJobId, generateInternalJobId, guard, DEV_SHEET_ID }';
    }
    return '// Source: ' + file + '\nconst ' + names[file] + ' = (function() {\n' + code + '\nreturn ' + exports + ';\n})();';
  });

  return '/* GENERATED by node scripts/build-s05.cjs — do not edit. */\nvar S05Core = (function() {\n' + sections.join('\n') + '\nreturn { createIntakeProcessor: m1.createIntakeProcessor, validateIntake: m1.validateIntake, intakeHash: m1.intakeHash, buildIntakeRecord: m1.buildIntakeRecord, guard: m1.guard, DEV_SHEET_ID: m1.DEV_SHEET_ID, buildSyntheticMapping: m0.buildSyntheticMapping, applyMappings: m0.applyMappings, resolveBookingJob: m0.resolveBookingJob, generateJobId: m0.generateJobId, generateInternalJobId: m0.generateInternalJobId, generateCustomerId: m0.generateCustomerId };\n})();\n';
}

if (require.main === module) {
  fs.writeFileSync('apps-script/s05/S05Core.gs', buildS05Core());
  console.log('Built apps-script/s05/S05Core.gs');
}

module.exports = { buildS05Core };
