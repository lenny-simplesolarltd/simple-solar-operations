const fs = require('node:fs'), schema = require('../schema/tables.json');
const names = ['Outbox', 'CalendarLinks', 'AuditEvents', 'ReleaseModes', 'People'];
const headers = Object.fromEntries(names.map(n => [n, schema.tables.find(t => t.name === n).columns.map(c => c.name)]));
const files = ['calendar/service.js', 'calendar/cloud-adapter.js'];
const text = '/* Generated by npm run build:calendar. DEV calendar write service; LIVE only via S01_CONFIG.calendarMode. */\nvar CAL_HEADERS=' + JSON.stringify(headers) + ';\n' +
  files.map(f => fs.readFileSync(f, 'utf8').replace(/^'use strict';\n/m, '').replace(/^if \(typeof module !== 'undefined'\) \{[\s\S]*?\n\}\n?/m, '')).join('\n');
fs.mkdirSync('apps-script/calendar', { recursive: true });
fs.writeFileSync('apps-script/calendar/CalendarSync.js', text);
